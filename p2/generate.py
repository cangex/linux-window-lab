#!/usr/bin/env python3
"""Generate the shared C constants from the static partition manifest."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent
p = json.loads((root/'partition.json').read_text())
v = {k: int(x,0) if isinstance(x,str) and x.startswith('0x') else x for k,x in p.items()}
b = v['memory_base']
assert b % (1<<30) == 0 and v['memory_size'] == 256<<20
assert v['boot_cpu'] in v['offline_cpus'] and not set(v['offline_cpus']) & set(v['linux_cpus'])
assert v['disk_offset']+v['disk_size'] <= v['hob_offset'] < v['acpi_offset'] < v['stack_offset']
assert v['stack_offset']+v['stack_size'] <= v['free_offset'] < v['memory_size']
d={'BASE':b,'SIZE':v['memory_size'],'END':b+v['memory_size'],'ENTRY':b+v['entry_offset'],
   'CORE':b+v['core_offset'],'FV':b+v['fv_offset'],'DISK':b+v['disk_offset'],
   'DISK_SIZE':v['disk_size'],'HOB':b+v['hob_offset'],'ACPI':b+v['acpi_offset'],
   'STACK_BASE':b+v['stack_offset'],'STACK':b+v['stack_offset']+v['stack_size'],
   'FREE':b+v['free_offset'],'VIRTUAL_OFFSET':v['runtime_virtual_offset'],'SERIAL':v['serial_io'],
   'APIC':v['apic_id'],'CPU':v['boot_cpu'],'LAPIC':v['lapic_mmio']}
(root/'LwPartitionPkg/Include/Platform.h').write_text('// Generated by p2/generate.py; edit partition.json.\n#pragma once\n'+''.join(f'#define LW_{k} 0x{x:x}ULL\n' for k,x in d.items()))
(root/'platform.inc').write_text('; Generated from partition.json\n'+''.join(f'%define LW_{k} 0x{x:x}\n' for k,x in d.items()))
